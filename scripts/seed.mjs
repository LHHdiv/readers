async function write(rel, text) {
  const dest = join(root, rel);
  await mkdir(dirname(dest), { recursive: true });
  await writeFile(dest, text, "utf8");
}

let chapterCount = 0;
for (const book of books) {
  await write(
    `content/books/${book.id}.md`,
    fm({
      no: book.no,
      title: book.title,
      en: book.en,
      pattern: book.pattern,
      hue: book.hue,
      hue2: book.hue2,
      cat: book.cat,
      level: book.level,
      updated: book.updated,
      sub: book.sub,
      intro: book.intro,
      order: book.order,
    }),
  );
  let order = 0;
  for (const [vi, vol] of book.vols.entries()) {
    for (const ch of vol.chs) {
      order += 1;
      const slug = `ch${String(order).padStart(2, "0")}`;
      const key = `${book.id}/${slug}`;
      const body =
        featured[key] ??
        lesson({
          title: ch.title,
          summary: ch.summary,
          points: ch.points,
          paras: ch.paras ?? [],
        });
      await write(
        `content/chapters/${book.id}/${slug}.md`,
        fm({
          book: book.id,
          vol: vol.t,
          volOrder: vi + 1,
          order,
          title: ch.title,
          summary: ch.summary,
          points: ch.points,
        }) + body.trim() + "\n",
      );
      chapterCount += 1;
    }
  }
}

for (const item of journal) {
  await write(
    `content/journal/${item.file}`,
    fm({
      date: item.date,
      title: item.title,
      image: item.image,
      order: item.order,
    }) + item.body + "\n",
  );
}

